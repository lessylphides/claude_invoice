export const LUNAR = {
  2026: { seol: '2026-02-17', chuseok: '2026-09-25' },
  2027: { seol: '2027-02-07', chuseok: '2027-09-15' },
  2028: { seol: '2028-01-27', chuseok: '2028-10-03' },
  2029: { seol: '2029-02-13', chuseok: '2029-09-22' },
  2030: { seol: '2030-02-03', chuseok: '2030-09-12' },
};

const dayN = (ymd) => Math.round(Date.parse(`${ymd}T00:00:00Z`) / 86400000);
const md = (ymd) => ymd.slice(5); // 'MM-DD'
const inMd = (ymd, from, to) => md(ymd) >= from && md(ymd) <= to;
/** 명절 10일 전 ~ 2일 뒤 */
const nearHoliday = (ymd, key) => {
  const h = LUNAR[ymd.slice(0, 4)]?.[key];
  if (!h) return false;
  const diff = dayN(ymd) - dayN(h);
  return diff >= -10 && diff <= 2;
};

